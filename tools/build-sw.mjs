// Writes sw.js: precaches every file the game needs so it works offline.
// The cache name embeds a hash of the files, so each release refreshes it.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const files = ['index.html', 'manifest.webmanifest'];
const walk = (dir) => {
  for (const f of fs.readdirSync(path.join(root, dir))) {
    const rel = path.join(dir, f);
    const st = fs.statSync(path.join(root, rel));
    if (st.isDirectory()) walk(rel);
    else if (/\.(js|css|woff2|png|svg|txt)$/.test(f)) files.push(rel.split(path.sep).join('/'));
  }
};
walk('src');
walk('assets');
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 10);
const body = `// Generated by tools/build-sw.mjs — offline support for Lumignons.
const CACHE = 'lumignons-${version}';
const FILES = ${JSON.stringify(['./', ...files.map((f) => './' + f)], null, 2)};

self.addEventListener('install', (e) => {
  // cache: 'reload' skips the HTTP cache, so a release never precaches stale files.
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('lumignons-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      });
    }),
  );
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), body);
console.log(`sw.js: ${files.length} files, cache ${version}`);
