// Verifies every level of the campaign and (re)writes src/data/solutions.js.
//   node tools/verify-levels.mjs            verify + write
//   node tools/verify-levels.mjs --check    verify against the stored file only
import fs from 'node:fs';
import { allLevels } from '../src/data/levels.js';
import { parseLevel, validateLevel, simulate, PIECE } from '../src/engine/core.js';
import { solve, checkSolution } from '../src/engine/solver.js';
import { overlay } from './lib.mjs';

const checkOnly = process.argv.includes('--check');
const out = {};
let problems = 0;
const t0 = Date.now();
for (const def of allLevels()) {
  const L = parseLevel(def);
  const errs = validateLevel(L);
  const empty = simulate(L, []);
  if (empty.result === 'win') errs.push('solvable with no piece at all');
  const one = solve(L, { countCap: 1, timeLimitMs: 300000 });
  const best = solve(L, { fireflies: true, countCap: 6, timeLimitMs: 300000 });
  if (one.min === null) errs.push('NOT SOLVABLE');
  if (best.min === null) errs.push('fireflies cannot all be caught within the inventory');
  if (one.timedOut || best.timedOut) errs.push('solver timeout');
  let sol = null;
  if (best.solutions[0]) {
    sol = best.solutions[0];
    const c = checkSolution(L, sol);
    if (!c.ok || !c.sim.allFireflies) errs.push('stored solution does not check out');
  }
  const total = L.inventory.arrow + L.inventory.lily + L.inventory.mushroom + L.inventory.daisy;
  const line = `${def.id.padEnd(5)} ${String(L.w + 'x' + L.h).padEnd(5)} pieces ${String(total).padStart(2)}  ★ ${one.min ?? '-'}  ★★★ ${best.min ?? '-'} (${best.solutions.length}${best.solutions.length >= 6 ? '+' : ''} sol)`;
  console.log((errs.length ? '✗ ' : '✓ ') + line + (errs.length ? '  ← ' + errs.join('; ') : ''));
  if (errs.length) {
    problems++;
    if (sol) console.log(overlay(L, sol));
  }
  out[def.id] = { min: one.min, par: best.min, n: best.solutions.length, sol: sol ? sol.map((p) => [p.idx, p.type, p.type === PIECE.ARROW ? p.dir : 0]) : [] };
}
console.log(`${Object.keys(out).length} levels checked in ${((Date.now() - t0) / 1000).toFixed(1)}s, ${problems} problem(s).`);
if (!checkOnly) {
  const body = `// Generated by tools/verify-levels.mjs — do not edit by hand.
// For each level: min = fewest pieces to win, par = fewest pieces for a perfect run,
// n = number of distinct perfect layouts found (capped at 6), sol = one perfect layout [cell, type, dir].
export const SOLUTIONS = ${JSON.stringify(out)};
`;
  fs.writeFileSync(new URL('../src/data/solutions.js', import.meta.url), body);
}
process.exit(problems ? 1 : 0);
